/* Skills for a branch, plus any skills the student already saved. */
function skillsForBranch(branch, alreadySelected = []) {
    const list = [...(SKILLS_BY_BRANCH[branchGroup(branch)] || SKILLS_BY_BRANCH.all)];
    alreadySelected.forEach(s => { if (s && !list.includes(s)) list.push(s); });
    return list;
}
