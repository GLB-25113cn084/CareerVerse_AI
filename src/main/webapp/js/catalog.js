/* Same rules as CareerData.branchGroup() in Java. */
function branchGroup(branch) {
    const b = String(branch || '').toLowerCase();
    if (!b.trim()) return 'all';
    if (/computer|information technology|artificial|data science|cyber|software/.test(b)) return 'cs';
    if (b.includes('electrical')) return 'ee';
    if (/electronics|communication|instrumentation/.test(b)) return 'ece';
    if (/mechanical|automobile|production|mechatronics|aeronautical/.test(b)) return 'me';
    if (b.includes('civil')) return 'civil';
    return 'all';
}

